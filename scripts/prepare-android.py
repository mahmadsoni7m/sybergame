from pathlib import Path
import re

root = Path('android')
manifest = root / 'app/src/main/AndroidManifest.xml'
if manifest.exists():
    text = manifest.read_text()
    text = re.sub(r'(<activity\b[^>]*android:name="\.MainActivity"[^>]*)(>)',
                  lambda m: m.group(1) + ' android:screenOrientation="landscape"' + m.group(2)
                  if 'android:screenOrientation=' not in m.group(1) else m.group(0), text, count=1)
    manifest.write_text(text)

candidates = list((root / 'app/src/main/java').rglob('MainActivity.java'))
if not candidates:
    raise SystemExit('MainActivity.java was not generated by Capacitor')
main = candidates[0]
main.write_text('''package com.cybervoid.survivor;\n\nimport android.os.Bundle;\nimport android.view.View;\nimport android.view.WindowManager;\nimport com.getcapacitor.BridgeActivity;\n\npublic class MainActivity extends BridgeActivity {\n  @Override\n  public void onCreate(Bundle savedInstanceState) {\n    super.onCreate(savedInstanceState);\n    getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);\n    hideSystemUI();\n  }\n\n  private void hideSystemUI() {\n    getWindow().getDecorView().setSystemUiVisibility(\n      View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY\n      | View.SYSTEM_UI_FLAG_LAYOUT_STABLE\n      | View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION\n      | View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN\n      | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION\n      | View.SYSTEM_UI_FLAG_FULLSCREEN\n    );\n  }\n\n  @Override\n  public void onWindowFocusChanged(boolean hasFocus) {\n    super.onWindowFocusChanged(hasFocus);\n    if (hasFocus) hideSystemUI();\n  }\n}\n''')
